<?php
// Versão 4 do esquema: assistente com IA (Etapa 4c, D70).
//   * assistente_faq: perguntas e respostas que o dono escreve (entram no prompt);
//   * assistente_fluxos: regras "quando o cliente pedir X, faça Y" (os "playbooks", em texto);
//   * ia_uso: uma linha por resposta da IA (modelo, tokens e custo real devolvido pelo OpenRouter), para o gasto e o teto mensal.
// O mesmo SQL vale no SQLite e no Postgres, só a coluna "id" muda. Banco novo já nasce assim (data/schema.*.sql).
declare(strict_types=1);

return static function (PDO $pdo): void {
    $id = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql'
        ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'INTEGER PRIMARY KEY AUTOINCREMENT';

    $pdo->exec("CREATE TABLE assistente_faq (
      id       {$id},
      pergunta TEXT NOT NULL,
      resposta TEXT NOT NULL,
      ativo    INTEGER NOT NULL DEFAULT 1,
      ordem    INTEGER NOT NULL DEFAULT 0
    )");
    $pdo->exec("CREATE TABLE assistente_fluxos (
      id     {$id},
      titulo TEXT NOT NULL,
      quando TEXT NOT NULL,
      passos TEXT NOT NULL,
      ativo  INTEGER NOT NULL DEFAULT 1,
      ordem  INTEGER NOT NULL DEFAULT 0
    )");
    $pdo->exec("CREATE TABLE ia_uso (
      id            {$id},
      criado_em     TEXT NOT NULL,
      origem        TEXT NOT NULL,
      telefone      TEXT,
      modelo        TEXT NOT NULL,
      tokens_in     INTEGER NOT NULL DEFAULT 0,
      tokens_out    INTEGER NOT NULL DEFAULT 0,
      custo_micro   INTEGER NOT NULL DEFAULT 0,
      duracao_ms    INTEGER NOT NULL DEFAULT 0,
      ferramentas   TEXT,
      erro          TEXT
    )");
    $pdo->exec('CREATE INDEX idx_ia_uso_criado ON ia_uso (criado_em)');
    $pdo->exec('CREATE INDEX idx_ia_uso_telefone ON ia_uso (telefone, criado_em)');
};
