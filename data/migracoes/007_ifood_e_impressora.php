<?php
// Versão 7 do esquema: integração com o iFood (D76 a D78) e o agente de impressão do computador da loja (D79 a D81).
//   * ifood_conexao: a ligação da loja com a Merchant API do iFood (uma linha só). Os tokens nunca saem para o painel.
//   * ifood_pedidos: o que o pedido do iFood tem e o nosso não tem (número do iFood, pago online, localizador, código de coleta).
//   * ifood_eventos: cada evento recebido do polling, para o mesmo evento nunca ser processado duas vezes.
//   * ifood_acoes: o que o painel precisa contar ao iFood (confirmar, iniciar preparo, pronto, saiu, cancelar), com nova tentativa.
//   * impressao_trabalhos: a fila de comandas do agente de impressão (automáticas, reimpressões e testes).
// O mesmo SQL vale no SQLite e no Postgres, só a coluna "id" muda. Banco novo já nasce assim (data/schema.*.sql).
declare(strict_types=1);

return static function (PDO $pdo): void {
    $id = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql'
        ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'INTEGER PRIMARY KEY AUTOINCREMENT';

    $pdo->exec("CREATE TABLE ifood_conexao (
      id                 INTEGER PRIMARY KEY CHECK (id = 1),
      estado             TEXT NOT NULL DEFAULT 'desconectado',
      merchant_id        TEXT,
      merchant_nome      TEXT,
      access_token       TEXT,
      token_expira_em    TEXT,
      refresh_token      TEXT,
      user_code          TEXT,
      verificador        TEXT,
      url_autorizacao    TEXT,
      codigo_expira_em   TEXT,
      proximo_polling_em TEXT,
      ultimo_polling_em  TEXT,
      ultimo_erro        TEXT,
      ultimo_erro_em     TEXT,
      atualizado_em      TEXT NOT NULL
    )");
    $pdo->exec("CREATE TABLE ifood_pedidos (
      pedido_id       INTEGER PRIMARY KEY REFERENCES pedidos (id) ON DELETE CASCADE,
      ifood_id        TEXT NOT NULL UNIQUE,
      display_id      TEXT NOT NULL,
      merchant_id     TEXT,
      tipo            TEXT NOT NULL,
      agendado_para   TEXT,
      entregue_por    TEXT,
      pago_online     INTEGER NOT NULL DEFAULT 0,
      pagamento_texto TEXT NOT NULL DEFAULT '',
      telefone        TEXT NOT NULL DEFAULT '',
      localizador     TEXT NOT NULL DEFAULT '',
      codigo_coleta   TEXT NOT NULL DEFAULT '',
      status_ifood    TEXT NOT NULL DEFAULT 'PLACED',
      confirmado_em   TEXT,
      simulado        INTEGER NOT NULL DEFAULT 0,
      dados           TEXT NOT NULL,
      criado_em       TEXT NOT NULL,
      atualizado_em   TEXT NOT NULL
    )");
    $pdo->exec("CREATE TABLE ifood_eventos (
      id           TEXT PRIMARY KEY,
      codigo       TEXT NOT NULL,
      ifood_pedido TEXT NOT NULL,
      recebido_em  TEXT NOT NULL,
      resultado    TEXT NOT NULL DEFAULT ''
    )");
    $pdo->exec('CREATE INDEX idx_ifood_eventos_recebido ON ifood_eventos (recebido_em)');
    $pdo->exec("CREATE TABLE ifood_acoes (
      id          {$id},
      pedido_id   INTEGER NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
      acao        TEXT NOT NULL,
      corpo       TEXT,
      estado      TEXT NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente', 'feita', 'falhou')),
      tentativas  INTEGER NOT NULL DEFAULT 0,
      proxima_em  TEXT NOT NULL,
      erro        TEXT,
      criado_em   TEXT NOT NULL,
      feita_em    TEXT
    )");
    $pdo->exec('CREATE INDEX idx_ifood_acoes_estado ON ifood_acoes (estado, proxima_em)');
    $pdo->exec("CREATE TABLE impressao_trabalhos (
      id          {$id},
      pedido_id   INTEGER REFERENCES pedidos (id) ON DELETE CASCADE,
      tipo        TEXT NOT NULL CHECK (tipo IN ('auto', 'reimpressao', 'teste')),
      estado      TEXT NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente', 'enviado', 'feito', 'falhou')),
      tentativas  INTEGER NOT NULL DEFAULT 0,
      erro        TEXT,
      criado_em   TEXT NOT NULL,
      enviado_em  TEXT,
      feito_em    TEXT
    )");
    $pdo->exec('CREATE INDEX idx_impressao_estado ON impressao_trabalhos (estado)');
};
