<?php
// Versão 5 do esquema: crédito do cliente no assistente com IA (D72).
//   * ia_recargas: o que o cliente pagou (você registra cada recarga na tela Assistente). O saldo é o total das recargas
//     menos o gasto do assistente no WhatsApp desde a primeira recarga. Sem nenhuma recarga registrada, o controle fica desligado.
// O mesmo SQL vale no SQLite e no Postgres, só a coluna "id" muda. Banco novo já nasce assim (data/schema.*.sql).
declare(strict_types=1);

return static function (PDO $pdo): void {
    $id = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql'
        ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'INTEGER PRIMARY KEY AUTOINCREMENT';

    $pdo->exec("CREATE TABLE ia_recargas (
      id          {$id},
      criado_em   TEXT NOT NULL,
      valor_micro INTEGER NOT NULL CHECK (valor_micro > 0),
      nota        TEXT NOT NULL DEFAULT ''
    )");
};
