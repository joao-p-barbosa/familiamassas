<?php
// Versão 11 do esquema: faturamento (D101).
//   * fechamentos_caixa: a conferência da gaveta de cada dia. Reabrir não apaga: marca cancelado_em (fica no histórico).
//   * cancelamentos: cada cancelamento de venda, total ou parcial, com os itens, o valor e o motivo.
//   * itens_pedido.quantidade_cancelada: quantas unidades do item já foram canceladas (para não cancelar a mesma duas vezes).
// O mesmo SQL vale no SQLite e no Postgres, só a coluna "id" muda. Banco novo já nasce assim (data/schema.*.sql).
declare(strict_types=1);

return static function (PDO $pdo): void {
    $id = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql'
        ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    $pdo->exec("CREATE TABLE fechamentos_caixa (
      id                       {$id},
      data                     TEXT NOT NULL,
      caixa_inicial_centavos   INTEGER NOT NULL,
      vendas_dinheiro_centavos INTEGER NOT NULL,
      retiradas_centavos       INTEGER NOT NULL,
      esperado_centavos        INTEGER NOT NULL,
      contado_centavos         INTEGER NOT NULL,
      diferenca_centavos       INTEGER NOT NULL,
      faturamento_centavos     INTEGER NOT NULL,
      observacao               TEXT NOT NULL DEFAULT '',
      fechado_por              INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
      fechado_em               TEXT NOT NULL,
      cancelado_em             TEXT,
      cancelado_por            INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
      motivo_cancelamento      TEXT
    )");
    $pdo->exec('CREATE INDEX idx_fechamentos_data ON fechamentos_caixa (data)');
    $pdo->exec("CREATE TABLE cancelamentos (
      id             {$id},
      pedido_id      INTEGER REFERENCES pedidos (id) ON DELETE CASCADE,
      atendimento_id INTEGER REFERENCES atendimentos (id) ON DELETE CASCADE,
      tipo           TEXT NOT NULL CHECK (tipo IN ('total', 'parcial')),
      valor_centavos INTEGER NOT NULL CHECK (valor_centavos >= 0),
      itens          TEXT NOT NULL,
      motivo         TEXT NOT NULL,
      usuario_id     INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
      criado_em      TEXT NOT NULL
    )");
    $pdo->exec('ALTER TABLE itens_pedido ADD COLUMN quantidade_cancelada INTEGER NOT NULL DEFAULT 0');
};
